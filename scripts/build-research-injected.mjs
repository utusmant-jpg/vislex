// Builds src-tauri/resources/research/injected-script.js from the Playwright injected script
// shipped in the locked playwright-core package (Apache-2.0). The research browser runs it in
// an isolated DevTools world to produce accessibility snapshots with element refs.
//
// Usage: node scripts/build-research-injected.mjs [--check]
//   --check  fails if the committed file differs from a fresh build (reproducibility).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const packageDir = join(root, 'node_modules', 'playwright-core');
const { version, license } = JSON.parse(readFileSync(join(packageDir, 'package.json'), 'utf8'));
if (license !== 'Apache-2.0') throw new Error(`Unexpected playwright-core license ${license}`);
const locked = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8')).packages['node_modules/playwright-core']?.version;
if (locked !== version) throw new Error(`Installed playwright-core ${version} differs from package-lock ${locked}; run npm ci`);

// The injected script is embedded as a single string literal assigned to a module variable.
const bundle = readFileSync(join(packageDir, 'lib', 'coreBundle.js'), 'utf8');
const marker = '"packages/playwright-core/src/generated/injectedScriptSource.ts"() {';
const start = bundle.indexOf(marker);
if (start < 0) throw new Error('Injected script source not found in playwright-core');
const assignment = /(\w+) = ('(?:[^'\\]|\\.)*');/y;
assignment.lastIndex = bundle.indexOf('=', start) - bundle.slice(0, bundle.indexOf('=', start)).match(/\w+\s*$/)[0].length;
const match = assignment.exec(bundle);
if (!match) throw new Error('Injected script literal not parsed');
const source = vm.runInNewContext(match[2]);
if (!source.includes('ariaSnapshot(') || !source.includes('InjectedScript')) throw new Error('Injected script lacks ariaSnapshot');

const output = [
  `// Playwright ${version} injected script (Apache-2.0, Copyright Microsoft Corporation).`,
  '// Generated by scripts/build-research-injected.mjs; do not edit. Evaluates to the',
  '// InjectedScript class; the research browser instantiates it in an isolated world.',
  '(() => {',
  'const module = {};',
  source,
  'return module.exports.InjectedScript();',
  '})()',
  '',
].join('\n');

const target = join(root, 'src-tauri', 'resources', 'research', 'injected-script.js');
const digest = createHash('sha256').update(output).digest('hex');
if (process.argv.includes('--check')) {
  const current = readFileSync(target, 'utf8');
  if (current !== output) throw new Error('injected-script.js is not reproducible from the locked playwright-core');
  console.log(`injected-script.js reproducible (playwright-core ${version}, sha256 ${digest})`);
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
  console.log(`wrote ${target} (${output.length} bytes, playwright-core ${version}, sha256 ${digest})`);
}
